#!/usr/bin/env python3
"""Run minimocas on the validation days with the corrected demand clock.

Demand configurations: article/python/revision/rerun/work/conf_fixed/<date>.json, generated by
gen_configs.py with ``fixed_clock=True``: all 24 hourly OD values are used and OD hour h (start
label, local time) is injected in [h, h+1). This alignment was checked against the local-time
MTS profile of 10-14 February 2020 (see analysis/od_clock_check.py).

Cartography: the project graph in vars/ (commit a059fb0, 2024-05-20, 3,925 polylines) with its
barrier, no-turn and population files. Outputs are written outside the repository
(default $SIM_RUNS/carto2024) because they are large and derived from proprietary demand.

Usage: python3 model/analysis/run_corrected_sims.py [--out DIR] [--nproc N] [dates...]
"""
import argparse
import json
import subprocess
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parent))
from paths import ROOT, SIM_ENGINE, SIM_RUNS  # noqa: E402

RERUN = ROOT / "article/python/revision/rerun/work"
CONF = RERUN / "conf_fixed"
ENGINE = SIM_ENGINE
DATES = ["2020-02-10", "2020-02-11", "2020-02-12", "2020-02-13", "2020-02-14", "2020-02-15",
         "2020-02-16", "2020-02-17", "2021-06-28", "2021-06-29", "2021-06-30", "2021-07-01",
         "2021-07-02", "2021-07-03", "2021-07-04"]


def run(date, out):
    c = json.load(open(CONF / f"{date}.json"))
    for k in ["file_pro", "file_pnt", "file_barrier", "file_score_pop", "file_noturn"]:
        c[k] = str(ROOT / c[k].split("covid_hep/")[1])
    c.update(enable_gui=False, dump_state_dt=-1)
    tag = date.replace("-", "")[2:]
    c["state_basename"] = str(out / f"sim_{tag}")
    cfg = out / f"sim_{tag}.json"
    json.dump(c, open(cfg, "w"), indent=1)
    t0 = time.time()
    with open(out / f"sim_{tag}.log", "w") as log:
        r = subprocess.run([str(ENGINE), str(cfg)], stdout=log, stderr=subprocess.STDOUT, cwd=out)
    return date, r.returncode, round(time.time() - t0)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(SIM_RUNS / "carto2024"))
    ap.add_argument("--nproc", type=int, default=4)
    ap.add_argument("dates", nargs="*", default=DATES)
    a = ap.parse_args()
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    with ThreadPoolExecutor(a.nproc) as ex:
        for res in ex.map(lambda d: run(d, out), a.dates):
            print(*res, flush=True)


if __name__ == "__main__":
    main()
